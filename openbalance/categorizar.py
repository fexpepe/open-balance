def chave_aprendizado(descricao):
    """Estabelecimento ou pessoa: 'Pix enviado FULANO' e 'PIX ENVIADO | Fulano' caem na mesma chave."""
    nome_marca = regras.marca(regras.normalizar(descricao))
    contraparte = regras.nome_contraparte(descricao)
    return regras.chave_estabelecimento(contraparte or descricao, nome_marca)


def aprender(conexao):
    """{(chave, é_entrada): categoria} a partir do que já está no banco (ajuste manual > categoria gravada)."""
    ajustes = {r["transacao_id"]: r["categoria_id"] for r in conexao.execute(
        "SELECT transacao_id, categoria_id FROM ajustes WHERE categoria_id IS NOT NULL")}
    contagem = defaultdict(Counter)
    for r in conexao.execute("SELECT id, bruto FROM transacoes"):
        t = json.loads(r["bruto"])
        if t.get("_projetada"):
            continue
        categoria = ajustes.get(r["id"]) or t.get("categoryId")
        if not categoria or categoria == CAT_OUTROS:
            continue
        chave = chave_aprendizado(t.get("description"))
        if len(chave) >= 3:
            contagem[(chave, t.get("type") == "CREDIT")][categoria] += 1
    aprendido = {}
    for chave, votos in contagem.items():
        categoria, n = votos.most_common(1)[0]
        if n / sum(votos.values()) >= 0.6:
            aprendido[chave] = categoria
    return aprendido


def categorizar(descricao, entrada, cartao, aprendido):
    """Devolve (categoria, de onde veio: 'historico' | 'palavra' | 'padrao')."""
    d = regras.normalizar(descricao)
    if cartao and entrada and RE_PAGAMENTO_CARTAO.search(d):
        return CAT_PAGAMENTO_CARTAO, "palavra"
    if not cartao and regras.RE_FATURA.search(d):
        return CAT_PAGAMENTO_CARTAO, "palavra"
    categoria = aprendido.get((chave_aprendizado(descricao), entrada))
    if categoria:
        return categoria, "historico"
    for padrao, categoria in PALAVRAS:
        if padrao.search(d):
            return categoria, "palavra"
    return CAT_OUTROS, "padrao"


def operacao(descricao):
    d = regras.normalizar(descricao)
    return next((op for padrao, op in RE_OPERACAO if padrao.search(d)), None)
